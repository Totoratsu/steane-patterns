"""Build the root main.css from src/css/{tokens,main}.css. Qollab loads a root-level main.css next to
index.html but not stylesheets in subfolders. Fonts load from the raw GitHub URL on main.
Run after editing those CSS files: python scripts/build_css.py"""
import pathlib

RAW = "https://raw.githubusercontent.com/Totoratsu/steane-patterns/main/src"
root = pathlib.Path(__file__).resolve().parent.parent
css = "\n".join((root / "src/css" / f).read_text() for f in ("tokens.css", "main.css"))
header = "/* Generated by scripts/build_css.py from src/css/tokens.css + src/css/main.css. Edit those. */\n"
(root / "main.css").write_text(header + css.replace('url("../fonts/', f'url("{RAW}/fonts/'))
